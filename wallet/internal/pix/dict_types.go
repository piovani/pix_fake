package pix

import (
	"encoding/xml"
	"time"
)

type (
	KeyType     string
	AccountType string
	PersonType  string
)

const (
	KeyCPF   KeyType = "CPF"
	KeyCNPJ  KeyType = "CNPJ"
	KeyPhone KeyType = "PHONE"
	KeyEmail KeyType = "EMAIL"
	KeyEVP   KeyType = "EVP" // random key, generated by the DICT

	AccountChecking AccountType = "CACC"
	AccountPayment  AccountType = "TRAN"
	AccountSalary   AccountType = "SLRY"
	AccountSavings  AccountType = "SVGS"
	AccountOther    AccountType = "OTHR"

	NaturalPerson PersonType = "NATURAL_PERSON"
	LegalPerson   PersonType = "LEGAL_PERSON"
)

type EntryReason string

const (
	ReasonUserRequested EntryReason = "USER_REQUESTED"
	ReasonAccountClose  EntryReason = "ACCOUNT_CLOSURE"
	ReasonBranchMove    EntryReason = "BRANCH_TRANSFER"
	ReasonReconcile     EntryReason = "RECONCILIATION"
)

type Account struct {
	Participant   string // ISPB of the account provider
	Branch        string
	AccountNumber string
	AccountType   AccountType
	OpeningDate   time.Time
}

type Owner struct {
	Type        PersonType
	TaxIDNumber string
	Name        string
	TradeName   string // legal persons only
}

type Entry struct {
	Key              string // empty when creating a random (EVP) key
	KeyType          KeyType
	Account          Account
	Owner            Owner
	CreationDate     time.Time // answers only
	KeyOwnershipDate time.Time // answers only
}

type KeyStatus struct {
	Key      string
	HasEntry bool
}

const dictTimeLayout = "2006-01-02T15:04:05.000Z"

// dictTime writes dates in UTC with milliseconds.
type dictTime time.Time

func (t dictTime) MarshalText() ([]byte, error) {
	return []byte(time.Time(t).UTC().Format(dictTimeLayout)), nil
}

func (t *dictTime) UnmarshalText(b []byte) error {
	parsed, err := time.Parse(time.RFC3339, string(b))
	if err != nil {
		return err
	}
	*t = dictTime(parsed)
	return nil
}

type accountXML struct {
	Participant   string   `xml:"Participant"`
	Branch        string   `xml:"Branch,omitempty"`
	AccountNumber string   `xml:"AccountNumber"`
	AccountType   string   `xml:"AccountType"`
	OpeningDate   dictTime `xml:"OpeningDate"`
}

type ownerXML struct {
	Type        string `xml:"Type"`
	TaxIDNumber string `xml:"TaxIdNumber"`
	Name        string `xml:"Name"`
	TradeName   string `xml:"TradeName,omitempty"`
}

type entryXML struct {
	Key              string     `xml:"Key,omitempty"`
	KeyType          string     `xml:"KeyType"`
	Account          accountXML `xml:"Account"`
	Owner            ownerXML   `xml:"Owner"`
	CreationDate     *dictTime  `xml:"CreationDate,omitempty"`
	KeyOwnershipDate *dictTime  `xml:"KeyOwnershipDate,omitempty"`
}

type createEntryRequestXML struct {
	XMLName   xml.Name `xml:"CreateEntryRequest"`
	Entry     entryXML `xml:"Entry"`
	Reason    string   `xml:"Reason"`
	RequestID string   `xml:"RequestId"`
}

type updateEntryRequestXML struct {
	XMLName xml.Name    `xml:"UpdateEntryRequest"`
	Key     string      `xml:"Key"`
	Account *accountXML `xml:"Account,omitempty"`
	Owner   *ownerXML   `xml:"Owner,omitempty"`
	Reason  string      `xml:"Reason"`
}

type deleteEntryRequestXML struct {
	XMLName     xml.Name `xml:"DeleteEntryRequest"`
	Key         string   `xml:"Key"`
	Participant string   `xml:"Participant"`
	Reason      string   `xml:"Reason"`
}

type checkKeysRequestXML struct {
	XMLName xml.Name `xml:"CheckKeysRequest"`
	Keys    struct {
		Key []string `xml:"Key"`
	} `xml:"Keys"`
}

// entryResponseXML reads the create, get and update answers.
type entryResponseXML struct {
	CorrelationID string   `xml:"CorrelationId"`
	Entry         entryXML `xml:"Entry"`
}

type deleteEntryResponseXML struct {
	Key string `xml:"Key"`
}

type checkKeysResponseXML struct {
	Keys struct {
		Key []struct {
			Key      string `xml:",chardata"`
			HasEntry bool   `xml:"hasEntry,attr"`
		} `xml:"Key"`
	} `xml:"Keys"`
}

type problemXML struct {
	Type          string `xml:"type"`
	Title         string `xml:"title"`
	Status        int    `xml:"status"`
	Detail        string `xml:"detail"`
	CorrelationID string `xml:"correlationId"`
	Violations    struct {
		Violation []struct {
			Reason   string `xml:"reason"`
			Value    string `xml:"value"`
			Property string `xml:"property"`
		} `xml:"violation"`
	} `xml:"violations"`
}

func (a Account) toXML() accountXML {
	return accountXML{Participant: a.Participant, Branch: a.Branch, AccountNumber: a.AccountNumber,
		AccountType: string(a.AccountType), OpeningDate: dictTime(a.OpeningDate)}
}

func (o Owner) toXML() ownerXML {
	return ownerXML{Type: string(o.Type), TaxIDNumber: o.TaxIDNumber, Name: o.Name, TradeName: o.TradeName}
}

func (e entryXML) toEntry() Entry {
	out := Entry{
		Key:     e.Key,
		KeyType: KeyType(e.KeyType),
		Account: Account{
			Participant: e.Account.Participant, Branch: e.Account.Branch, AccountNumber: e.Account.AccountNumber,
			AccountType: AccountType(e.Account.AccountType), OpeningDate: time.Time(e.Account.OpeningDate),
		},
		Owner: Owner{
			Type: PersonType(e.Owner.Type), TaxIDNumber: e.Owner.TaxIDNumber, Name: e.Owner.Name, TradeName: e.Owner.TradeName,
		},
	}
	if e.CreationDate != nil {
		out.CreationDate = time.Time(*e.CreationDate)
	}
	if e.KeyOwnershipDate != nil {
		out.KeyOwnershipDate = time.Time(*e.KeyOwnershipDate)
	}
	return out
}
