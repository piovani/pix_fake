package dict

import (
	"context"
	"errors"
	"time"
)

const maxCheckKeys = 200

// Repository abstracts the storage of entries.
type Repository interface {
	// Create stores the entry. It returns ErrKeyExists or ErrRequestIDUsed on conflict.
	Create(ctx context.Context, e Entry, requestID string) error
	Get(ctx context.Context, key string) (Entry, error)
	GetByRequestID(ctx context.Context, participant, requestID string) (Entry, error)
	Update(ctx context.Context, e Entry) error
	Delete(ctx context.Context, key string) error
	// Existing returns the subset of keys that have an entry.
	Existing(ctx context.Context, keys []string) (map[string]bool, error)
}

type Service struct {
	repo   Repository
	now    func() time.Time
	newEVP func() string
}

func NewService(repo Repository) *Service {
	return &Service{repo: repo, now: time.Now, newEVP: NewEVP}
}

type CreateEntryInput struct {
	Entry     Entry // Key is empty for EVP keys (generated by the DICT)
	Reason    Reason
	RequestID string
}

// CreateEntry creates an entry on behalf of the participant caller. It is idempotent
// per (caller, RequestID).
func (s *Service) CreateEntry(ctx context.Context, caller string, in CreateEntryInput) (Entry, error) {
	e := in.Entry

	var v violations
	switch {
	case !validKeyType(e.KeyType):
		v.add("entry.keyType", string(e.KeyType), "Unknown key type")
	case e.KeyType == KeyEVP:
		if e.Key != "" {
			v.add("entry.key", e.Key, "Key must be empty for EVP: it is generated by DICT")
		}
	default:
		validateKey("entry.key", e.KeyType, e.Key, &v)
		validateKeyOwner(e.KeyType, e.Key, e.Owner, &v)
	}
	validateAccount("entry.account", e.Account, &v)
	validateOwner("entry.owner", e.Owner, &v)
	validateReason("reason", in.Reason, createReasons(), &v)
	validateRegexp("requestId", in.RequestID, requestIDRe, &v)
	if len(v) > 0 {
		return Entry{}, invalid(KindEntryInvalid, "Entry has invalid fields", v)
	}
	if e.Account.Type == AccountSalary {
		return Entry{}, newError(KindAccountTypeInvalid, "Entries cannot be created for accounts of type SLRY")
	}
	if e.Account.Participant != caller {
		return Entry{}, newError(KindForbidden, "Participant is not allowed to create entries for another participant")
	}

	if prev, err := s.repo.GetByRequestID(ctx, caller, in.RequestID); err == nil {
		return replay(prev, e)
	} else if !errors.Is(err, ErrNotFound) {
		return Entry{}, err
	}

	if e.KeyType == KeyEVP {
		e.Key = s.newEVP()
	}
	e.CreationDate = s.now().UTC().Truncate(time.Millisecond)
	e.KeyOwnershipDate = e.CreationDate

	switch err := s.repo.Create(ctx, e, in.RequestID); {
	case err == nil:
		return e, nil
	case errors.Is(err, ErrKeyExists):
		return Entry{}, newError(KindConflict, "Key is already registered")
	case errors.Is(err, ErrRequestIDUsed): // concurrent retry with the same RequestId
		prev, err := s.repo.GetByRequestID(ctx, caller, in.RequestID)
		if err != nil {
			return Entry{}, err
		}
		return replay(prev, e)
	default:
		return Entry{}, err
	}
}

// replay handles a repeated RequestId: it returns the entry already created if the
// parameters are the same, otherwise RequestIdAlreadyUsed.
func replay(prev, req Entry) (Entry, error) {
	same := (req.Key == "" || req.Key == prev.Key) &&
		req.KeyType == prev.KeyType &&
		req.Owner == prev.Owner &&
		sameAccount(req.Account, prev.Account)
	if !same {
		return Entry{}, newError(KindRequestIDAlreadyUsed, "RequestId was already used with different parameters")
	}
	return prev, nil
}

func sameAccount(a, b Account) bool {
	return a.Participant == b.Participant && a.Branch == b.Branch &&
		a.AccountNumber == b.AccountNumber && a.Type == b.Type &&
		a.OpeningDate.Equal(b.OpeningDate)
}

// LookupEntry is the DICT query that a payer's participant makes before a payment.
// An entry held by the requesting participant itself cannot be queried: a payment
// between two customers of the same participant is a book transfer, settled
// internally, and must not use the DICT (error EntryCannotBeQueriedForBookTransfer).
func (s *Service) LookupEntry(ctx context.Context, requestingParticipant, key string) (Entry, error) {
	e, err := s.GetEntry(ctx, key)
	if err != nil {
		return Entry{}, err
	}
	if e.Account.Participant == requestingParticipant {
		return Entry{}, newError(KindBookTransfer,
			"The entry is held by the same participant as the payer: payments between customers of the same "+
				"participant are settled internally and must not query the DICT")
	}
	return e, nil
}

// GetEntry reads the entry of a key, without any participant rule.
func (s *Service) GetEntry(ctx context.Context, key string) (Entry, error) {
	if err := checkKeyFormat(key); err != nil {
		return Entry{}, err
	}
	return s.find(ctx, key)
}

type UpdateEntryInput struct {
	Key     string
	Account *Account // optional
	Owner   *Owner   // optional: only Name and TradeName can change
	Reason  Reason
}

// UpdateEntry updates the account, name and trade name of one of the caller's entries.
func (s *Service) UpdateEntry(ctx context.Context, caller, key string, in UpdateEntryInput) (Entry, error) {
	if in.Key != key {
		return Entry{}, newError(KindBadRequest, "Key in the body does not match the key in the path")
	}
	kt, err := detectKeyType(key)
	if err != nil {
		return Entry{}, err
	}

	var v violations
	validateReason("reason", in.Reason, updateReasons(kt), &v)
	if in.Account != nil {
		validateAccount("account", *in.Account, &v)
	}
	if in.Owner != nil {
		validateOwner("owner", *in.Owner, &v)
	}
	if len(v) > 0 {
		return Entry{}, invalid(KindBadRequest, "Request has invalid fields", v)
	}

	e, err := s.find(ctx, key)
	if err != nil {
		return Entry{}, err
	}
	if e.Account.Participant != caller {
		return Entry{}, newError(KindForbidden, "Participant is not allowed to access this resource")
	}

	if in.Account != nil {
		if in.Account.Participant != e.Account.Participant {
			v.add("account.participant", in.Account.Participant, "Participant cannot be changed")
		}
		e.Account = *in.Account
	}
	if in.Owner != nil {
		if in.Owner.Type != e.Owner.Type || in.Owner.TaxID != e.Owner.TaxID {
			v.add("owner", in.Owner.TaxID, "Only Name and TradeName can be changed")
		}
		e.Owner.Name, e.Owner.TradeName = in.Owner.Name, in.Owner.TradeName
	}
	if len(v) > 0 {
		return Entry{}, invalid(KindBadRequest, "Request has invalid fields", v)
	}

	if err := s.repo.Update(ctx, e); err != nil {
		return Entry{}, mapNotFound(err)
	}
	return e, nil
}

type DeleteEntryInput struct {
	Key         string
	Participant string
	Reason      Reason
}

// DeleteEntry removes one of the caller's entries.
func (s *Service) DeleteEntry(ctx context.Context, caller, key string, in DeleteEntryInput) error {
	if in.Key != key {
		return newError(KindBadRequest, "Key in the body does not match the key in the path")
	}
	if err := checkKeyFormat(key); err != nil {
		return err
	}

	var v violations
	validateRegexp("participant", in.Participant, ispbRe, &v)
	validateReason("reason", in.Reason, deleteReasons(), &v)
	if len(v) > 0 {
		return invalid(KindBadRequest, "Request has invalid fields", v)
	}

	e, err := s.find(ctx, key)
	if err != nil {
		return err
	}
	if in.Participant != caller || e.Account.Participant != caller {
		return newError(KindForbidden, "Participant is not allowed to access this resource")
	}
	return mapNotFound(s.repo.Delete(ctx, key))
}

// CheckKeys reports which keys have an entry, keeping the order received.
func (s *Service) CheckKeys(ctx context.Context, keys []string) ([]KeyStatus, error) {
	if len(keys) == 0 || len(keys) > maxCheckKeys {
		return nil, newError(KindBadRequest, "Keys must contain between 1 and 200 items")
	}
	existing, err := s.repo.Existing(ctx, keys)
	if err != nil {
		return nil, err
	}
	out := make([]KeyStatus, len(keys))
	for i, k := range keys {
		out[i] = KeyStatus{Key: k, HasEntry: existing[k]}
	}
	return out, nil
}

func (s *Service) find(ctx context.Context, key string) (Entry, error) {
	e, err := s.repo.Get(ctx, key)
	return e, mapNotFound(err)
}

func mapNotFound(err error) error {
	if errors.Is(err, ErrNotFound) {
		return newError(KindNotFound, "Entry associated with given key does not exist")
	}
	return err
}

func detectKeyType(key string) (KeyType, error) {
	kt, ok := DetectKeyType(key)
	if !ok {
		var v violations
		v.add("key", key, "Value is not a valid CPF, CNPJ, PHONE, EMAIL or EVP key")
		return "", invalid(KindBadRequest, "Key is invalid", v)
	}
	return kt, nil
}

func checkKeyFormat(key string) error {
	_, err := detectKeyType(key)
	return err
}
